"""Import and apply the Zhengnanmen high-poly GLB in place.

The existing Great South Gate asset is left untouched.  A versioned mesh and
its imported materials/textures are created beside it, then the one existing
showcase actor is retargeted while retaining its actor identity, label, tags,
rotation, and scale.  Translation is recomputed only as needed to keep the
published placement center and terrain contact stable when the replacement
mesh has a different local origin.
"""
